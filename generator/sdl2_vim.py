#!/usr/bin/env python3

import sys;
import os;
import re;
from pycparser import c_parser, c_ast, parse_file, preprocess_file;

class visitor(c_ast.NodeVisitor):
	__slots__ = ['functions', 'types', 'enums', 'defines'];

	def __init__(self):
		self.functions = [];
		self.types = [];
		self.enums = [];
		self.defines = [];

	def visit_FuncDecl(self, node):
		t = None;
		if isinstance(node.type, c_ast.TypeDecl):
			t = node.type;
		elif isinstance(node.type, c_ast.PtrDecl):
			t = node.type.type;

		if t != None and isinstance(t, c_ast.TypeDecl):
			if t.declname[:4] == "SDL_":
				self.functions.append(t.declname);

	def visit_TypeDecl(self, node):
		if isinstance(node.type, c_ast.Enum):
			self.visit_Enum(node.type);

		if isinstance(node.declname, str) and len(node.declname) > 4 and (node.declname[:4] == "SDL_" or node.declname[:4] == "Sint" or node.declname[:4] == "Uint"):
			self.types.append(node.declname);

	def visit_Enumerator(self, node):
		if node.name[:3] == "SDL":
			self.enums.append(node.name);

	def visit_Enum(self, node):
		for v in node.values.enumerators:
			self.visit_Enumerator(v);

def generate_output(filename, v, sdl_version):
	m = int(sdl_version[0]);
	with open(filename, "wt") as f:
		f.write('''" Vim syntax file
" Language: C SDL%d library extension
" Generated By: sdl%d_vim.py
" Version: %s.%s.%s

''' % (m, m, *sdl_version));

		f.write("syn keyword sdl%d_function %s\n" % (m, " ".join(v.functions)));
		f.write("syn keyword sdl%d_type %s\n" % (m, " ".join(v.types)));
		f.write("syn keyword sdl%d_enum %s\n" % (m, " ".join(v.enums)));
		f.write("syn keyword sdl%d_define %s\n" % (m, " ".join(v.defines)));

		f.write('''
" Default highlighting
if version >= 508
  if version < 508
    command -nargs=+ HiLink hi link <args>
  else
    command -nargs=+ HiLink hi def link <args>
  endif
  HiLink sdl%d_function Function
  HiLink sdl%d_type Type
  HiLink sdl%d_enum Constant
  HiLink sdl%d_define Constant
  delcommand HiLink
endif
''' % (m, m, m, m));

def get_sdl_version(filename):
	# search for SDL_MAJOR_VERSION, SDL_MINOR_VERSION, SDL_PATCHLEVEL, SDL_MICRO_VERSION
	r = re.compile(r"^#define\s+SDL_(MAJOR_VERSION|MINOR_VERSION|PATCHLEVEL|MICRO_VERSION)\s+([0-9]+)$");
	version_major = None;
	version_minor = None;
	version_patchlevel = None;
	with open(filename) as f:
		for l in f:
			m = r.match(l);
			if(m):
				n = m.group(1);
				v = m.group(2);
				if(n == "MAJOR_VERSION"):
					version_major = v;
				elif(n == "MINOR_VERSION"):
					version_minor = v;
				elif(n == "PATCHLEVEL"):
					version_patchlevel = v;
				elif(n == "MICRO_VERSION"):
					# SDL3 uses MICRIO_VERSION instead of PATCHLEVEL
					version_patchlevel = v;
			if(version_major != None and version_minor != None \
					and version_patchlevel != None):
				break;
	return (version_major, version_minor, version_patchlevel);

def process_file(filename, incpath):
	sdl_version = get_sdl_version(os.path.join(incpath, "SDL_version.h"));

	cppargs = ["-Iutils/fake_libc_include", "-I%s" % incpath,
			"-DDECLSPEC=",
			"-D_SDL_platform_h=1",
			"-D_SDL_endian_h=1",
			"-DSDL_FORCE_INLINE=", "-D__attribute__(x)=",
			"-DSDL_FALLTHROUGH=",
	];
	ast = parse_file(filename, use_cpp=True, cpp_args=cppargs);
	v = visitor();
	v.visit(ast);

	del ast;

	cppargs.append("-dM");
	defines_text = preprocess_file(filename, cpp_args=cppargs);
	for s in defines_text.split("\n"):
		if s[:8] == "#define ":
			s = s[8:];
			m = re.search("(SDL_[A-Za-z0-9_]+)", s);
			if m != None:
				d = m.group(0);
				if isinstance(d, str) and len(d) > 4 and d == d.upper():
					v.defines.append(d);

	generate_output("sdl%d.vim" % (int(sdl_version[0])), v, sdl_version);

if len(sys.argv) > 1:
	process_file(os.path.join(sys.argv[1], "SDL.h"), sys.argv[1]);
else:
	print("use: %s path/to/SDL/headers/directory" % sys.argv[0]);
